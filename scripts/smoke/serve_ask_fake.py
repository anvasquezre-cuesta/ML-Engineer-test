"""Disposable smoke server: real retrieval with an explicitly fake generator.

Never import this module as a production server: it injects test-only answers.
"""

from fastapi import Request

from app.api.dependencies import get_ask_service
from app.main import app
from app.services.ask_service import AskService, CitationEvidence, GeneratedAnswer


class FakeGenerator:
    async def generate(self, question, context):
        return GeneratedAnswer("Synthetic smoke answer; not generated by an LLM.",
                               (CitationEvidence(context[0].citation_id, context[0].text[:100]),))


def fake_service(request: Request):
    return AskService(request.app.state.ingestion_service.embeddings,
                      request.app.state.retrieval_service, FakeGenerator())


app.dependency_overrides[get_ask_service] = fake_service
